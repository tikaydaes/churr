// The theme arithmetic, held to the server's own table tests. The cases
// are copied from internal/themes/palette/palette_test.go into
// palette_cases.json beside this file, and palette_corpus.json holds the
// Go package's answers for many generated themes (written by that
// package's TestAppCorpus), so the Dart port and the Go package cannot
// differ without a test failing. Luminances and ratios must be the same
// doubles as Go's, bit for bit, not merely close.
import 'dart:convert';
import 'dart:io';

import 'package:churr/core/themes/palette.dart';
import 'package:flutter_test/flutter_test.dart';

Map<String, dynamic> _load(String name) =>
    jsonDecode(File('test/core/themes/$name').readAsStringSync())
        as Map<String, dynamic>;

void main() {
  final cases = _load('palette_cases.json');
  final bases = (cases['bases'] as Map).map(
    (k, v) => MapEntry(k as String, Map<String, String>.from(v as Map)),
  );

  Map<String, String> theme(Map c) {
    final m = {...bases[c['base']]!};
    (c['with'] as Map? ?? const {}).forEach((k, v) {
      if (v == '') {
        m.remove(k);
      } else {
        m[k as String] = v as String;
      }
    });
    return m;
  }

  Colours parsed(Map c) => parseColours(theme(c)).$1!;

  test('ratio', () {
    for (final c in cases['ratio'] as List) {
      final r = ratio(Rgb.parse(c['a'])!, Rgb.parse(c['b'])!);
      expect(measured(r), c['want'], reason: '${c['a']} on ${c['b']}');
    }
  });

  test('mix', () {
    final m = cases['mix'] as Map;
    final a = Rgb.parse(m['a'])!, b = Rgb.parse(m['b'])!;
    for (final c in m['cases'] as List) {
      expect(mix(a, b, c['k'] as int).hex, c['want'], reason: 'mix ${c['k']}');
    }
  });

  group('parse', () {
    for (final c in cases['parse'] as List) {
      test(c['name'], () {
        final (got, fault) = parseColours(theme(c));
        final field = c['field'] as String;
        expect(fault?.key ?? '', field, reason: fault?.message);
        if (field.isEmpty) expect(got!.length, themeKeys.length);
      });
    }
    test('nothing is refused', () {
      expect(parseColours(null).$2, isNotNull);
      expect(parseColours({}).$2, isNotNull);
    });
    test('written back in lower case', () {
      final w = cases['parseWritesLowerCase'] as Map;
      expect(hexes(parsed(w))[w['key']], w['want']);
    });
  });

  test('derive', () {
    for (final c in cases['derive'] as List) {
      final d = derive(parsed(c));
      final got = {
        'onLav': d.onLav.hex,
        'onYel': d.onYel.hex,
        'faint': d.faint.hex,
        'edge': d.edge.hex,
        'yelInk': d.yelInk.hex,
      };
      for (final e in got.entries) {
        expect(e.value, c[e.key], reason: '${c['name']} ${e.key}');
      }
    }
  });

  group('check', () {
    for (final c in cases['check'] as List) {
      test(c['name'], () {
        final col = parsed(c);
        expect(
          kindFits(c['kind'], col),
          isTrue,
          reason: 'not a ${c['kind']} theme',
        );
        expect(check(c['kind'], col)?.message ?? '', c['want']);
      });
    }
  });

  test('kind fits', () {
    for (final c in cases['kindFits'] as List) {
      expect(kindFits(c['kind'], parsed(c)), c['want'], reason: '$c');
    }
  });

  test('every pairing names a token', () {
    final d = parsed({'base': 'guideDark'});
    final der = derive(d);
    for (final kind in [kindDark, kindLight]) {
      for (final p in pairings(kind)) {
        token(d, der, p.fore);
        token(d, der, p.back);
      }
    }
  });

  // Bit for bit: the same double, compared with ==, never a tolerance.
  // (Go writes 1.0 as 1, which jsonDecode reads as an int.)
  double num64(Object? v) => (v as num).toDouble();

  test('the linear light table is the Go package\'s, bit for bit', () {
    final want = _load('palette_corpus.json')['linear'] as List;
    expect(want.length, 256);
    for (var v = 0; v < 256; v++) {
      expect(
        linear(v) == num64(want[v]),
        isTrue,
        reason: 'linear($v): ${linear(v)}, Go ${want[v]}',
      );
    }
  });

  // Generated by running the Go package over themes made from a fixed
  // seed (see the file's `source`): every derived colour, every luminance
  // and ratio bit for bit, every ratio as the editor shows it, and the
  // refusal.
  test('the Go package\'s answers for generated themes', () {
    final corpus = _load('palette_corpus.json');
    var n = 0, exact = 0;
    for (final c in corpus['themes'] as List) {
      final kind = c['kind'] as String;
      final col = parseColours(Map<String, String>.from(c['colours'])).$1!;
      final d = derive(col);
      final want = c['derived'] as Map;
      expect(
        {
          'on-lav': d.onLav.hex,
          'on-cyan': d.onCyan.hex,
          'on-pink': d.onPink.hex,
          'on-yel': d.onYel.hex,
          'faint': d.faint.hex,
          'edge': d.edge.hex,
          'yel-ink': d.yelInk.hex,
        },
        want,
        reason: '${c['colours']}',
      );
      expect(kindFits(kind, col), c['kind_fits'], reason: '${c['colours']}');
      expect(
        [for (final m in measureAll(kind, col)) m.shown],
        c['measured'],
        reason: '${c['colours']}',
      );
      final lum = c['luminance'] as Map;
      for (final k in themeKeys) {
        final got = luminance(col[k]!), want = num64(lum[k]);
        expect(
          got == want,
          isTrue,
          reason: '${c['colours']}: luminance of $k $got, Go $want',
        );
        exact++;
      }
      final ratios = c['ratios'] as List;
      final all = measureAll(kind, col);
      expect(all.length, ratios.length);
      for (var j = 0; j < all.length; j++) {
        final got = all[j].ratio, want = num64(ratios[j]);
        expect(
          got == want,
          isTrue,
          reason: '${c['colours']}: ${all[j].pairing.name} $got, Go $want',
        );
        exact++;
      }
      expect(check(kind, col)?.message ?? '', c['refusal']);
      n++;
    }
    expect(n, greaterThan(500));
    expect(exact, greaterThan(20000));
  });

  group('fix', () {
    test('makes the smallest change that passes', () {
      final c = parsed({
        'base': 'guideDark',
        'with': {'pink': '#c0207f'},
      });
      final f = check(kindDark, c)!;
      expect(fixKey(f.pairing), 'pink');
      final fixed = fix(kindDark, c, 'pink')!;
      expect(check(kindDark, fixed), isNull);
      // One step less in the same direction would not do.
      final to = fixed['pink']!;
      int kOf(Rgb target) {
        for (var k = 1; k <= 100; k++) {
          if (mix(c['pink']!, target, k) == to) return k;
        }
        return -1;
      }

      final k = kOf(Rgb.white);
      expect(k, greaterThan(0));
      expect(
        check(kindDark, {...c, 'pink': mix(c['pink']!, Rgb.white, k - 1)}),
        isNotNull,
      );
    });

    test('fixes faint and edge through dim', () {
      final c = parsed({
        'base': 'guideDark',
        'with': {'dim': '#6a6890'},
      });
      final fixed = fix(kindDark, c, fixKey(check(kindDark, c)!.pairing))!;
      expect(check(kindDark, fixed), isNull);
      expect(fixed['bg'], c['bg']);
    });

    test('lavender is text: fixed until it reads on every ground', () {
      final c = parsed({
        'base': 'guideDark',
        'with': {'raise': '#0a0c1e', 'lav': '#7a6aff'},
      });
      final f = check(kindDark, c)!;
      expect(f.pairing.name, 'lav on panel');
      final fixed = fix(kindDark, c, fixKey(f.pairing))!;
      expect(valid(kindDark, fixed), isTrue);
      final old = parsed({
        'base': 'guideDark',
        'with': {'lav': '#7060c0'},
      });
      expect(valid(kindDark, fix(kindDark, old, 'lav')!), isTrue);
    });

    test('a passing theme is left as it is', () {
      final c = parsed({'base': 'guideLight'});
      expect(fix(kindLight, c, 'ink'), same(c));
    });
  });
}
