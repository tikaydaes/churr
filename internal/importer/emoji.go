// skinTones are the modifiers Slack writes after a name, as in
// `+1::skin-tone-3`.
var skinTones = map[string]string{
	"skin-tone-2": "\U0001F3FB", "skin-tone-3": "\U0001F3FC", "skin-tone-4": "\U0001F3FD",
	"skin-tone-5": "\U0001F3FE", "skin-tone-6": "\U0001F3FF",
}

// reactionEmoji turns the name of a Slack reaction into what Churr stores
// for one: the emoji itself for a standard one it knows, `:name:` otherwise.
func reactionEmoji(name string) string {
	base, tone, _ := strings.Cut(name, "::")
	e, ok := shortCodes[base]
	if !ok {
		return ":" + base + ":"
	}
	if t, ok := skinTones[tone]; ok {
		// The modifier follows the first character, before any
		// variation selector.
		r := []rune(e)
		if len(r) > 1 && r[1] == 0xFE0F {
			r = append(r[:1], r[2:]...)
		}
		return string(r[:1]) + t + string(r[1:])
	}
	return e
}
