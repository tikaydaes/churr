// What /help says, testdata/commands/help.json, is the one source both
// clients draw it from (rulings R67 and R74). These tests hold it complete
// against the command table, the deck registry and the grammars, and hold
// the clients' copies to it.

type helpExample struct {
	Type string `json:"type"`
	Then string `json:"then"`
}

type helpEntry struct {
	SameAs      string `json:"same_as"`
	Description string `json:"description"`
	Args        []struct {
		Name  string `json:"name"`
		About string `json:"about"`
	} `json:"args"`
	Examples []helpExample `json:"examples"`
	Where    string        `json:"where"`
	Who      string        `json:"who"`
	Related  []string      `json:"related"`
	More     string        `json:"more"`
}

type helpThing struct {
	ID      string       `json:"id"`
	Title   string       `json:"title"`
	Type    string       `json:"type"`
	Becomes string       `json:"becomes"`
	Popup   string       `json:"popup"`
	Example *helpExample `json:"example"`
	Sealed  *string      `json:"sealed"`
	Covers  []string     `json:"covers"`
	Live    string       `json:"live"`
}

type helpFile struct {
	Labels       map[string]string    `json:"labels"`
	Commands     map[string]helpEntry `json:"commands"`
	Decks        map[string]string    `json:"decks"`
	MeasureKinds []struct {
		Title string   `json:"title"`
		Units []string `json:"units"`
	} `json:"measure_kinds"`
	PopupRules []string    `json:"popup_rules"`
	Things     []helpThing `json:"things"`
	Markdown   []helpThing `json:"markdown"`
	Patterns   []struct {
		Expression string `json:"expression"`
		Want       string `json:"want"`
	} `json:"pattern_examples"`
}

const helpPath = "../../testdata/commands/help.json"

func readHelp(t *testing.T) helpFile {
	t.Helper()
	var h helpFile
	readJSON(t, helpPath, &h)
	return h
}

// The clients' copies are help.json as it is, as tools/help-gen/gen.py
// writes them: neither can say something the other does not.
func TestHelpCopiesAreTheSource(t *testing.T) {
	src, err := os.ReadFile(helpPath)
	if err != nil {
		t.Fatal(err)
	}
	body := strings.TrimRight(string(src), "\n")
	const gen = "// Generated by tools/help-gen/gen.py from testdata/commands/help.json.\n// Do not edit: change help.json and run the generator.\n\n"
	for path, want := range map[string]string{
		"../web/static/shared/helptext.js":           gen + "export const HELP = " + body + ";\n",
		"../../app/lib/core/commands/help_text.dart": gen + "/// What /help says: testdata/commands/help.json as it is.\nconst helpSource = r'''" + body + "''';\n",
	} {
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != want {
			t.Errorf("%s is not help.json as it is: run python3 tools/help-gen/gen.py", path)
		}
	}
}

// Every command of the table has a complete entry: a description, an
// argument explained for every part of its usage, at least two examples,
// where it works and who may use it; a row that is another name for a
// command points at one that has.
func TestHelpCoversEveryCommand(t *testing.T) {
	h := readHelp(t)
	byName := map[string]Command{}
	for _, c := range BuiltinCommands {
		byName[c.Name] = c
	}
	for _, c := range BuiltinCommands {
		e, ok := h.Commands[c.Name]
		if !ok {
			t.Errorf("/%s has no help", c.Name)
			continue
		}
		if e.SameAs != "" {
			to, ok := h.Commands[e.SameAs]
			if !ok || to.SameAs != "" || byName[e.SameAs].Name == "" {
				t.Errorf("/%s is the same as /%s, which has no entry of its own", c.Name, e.SameAs)
			}
			if !strings.Contains(c.Description, "(as /"+e.SameAs+")") {
				t.Errorf("/%s: the table does not say it is /%s: %q", c.Name, e.SameAs, c.Description)
			}
			continue
		}
		if strings.Count(e.Description, ". ")+1 < 2 && len(e.Description) < 80 {
			t.Errorf("/%s: the description is too short to say what it does and who sees it: %q", c.Name, e.Description)
		}
		if e.Where == "" || e.Who == "" {
			t.Errorf("/%s: where it works and who may use it are not said", c.Name)
		}
		if c.Hint != "" && len(e.Args) == 0 {
			t.Errorf("/%s takes %q but no argument is explained", c.Name, c.Hint)
		}
		for _, a := range e.Args {
			if a.Name == "" || a.About == "" {
				t.Errorf("/%s: an argument is not explained: %+v", c.Name, a)
			}
		}
		if len(e.Examples) < 2 {
			t.Errorf("/%s has %d examples, not at least two", c.Name, len(e.Examples))
		}
		for _, x := range e.Examples {
			if !strings.HasPrefix(strings.TrimLeft(x.Type, " "), "/") || x.Then == "" {
				t.Errorf("/%s: an example is not a command with what happens: %+v", c.Name, x)
			}
		}
		for _, r := range e.Related {
			if byName[r].Name == "" || r == c.Name {
				t.Errorf("/%s: related /%s is not another command of the table", c.Name, r)
			}
		}
		switch e.More {
		case "", "dice", "decks", "spreads", "mahjong":
		default:
			t.Errorf("/%s: no list is called %q", c.Name, e.More)
		}
	}
	for name := range h.Commands {
		if byName[name].Name == "" {
			t.Errorf("help for /%s, which is not in the table", name)
		}
	}
	// Every deck /draw knows is described, and nothing else.
	names := DeckNames()
	for _, d := range names {
		if h.Decks[d] == "" {
			t.Errorf("the deck %s is not described", d)
		}
	}
	if len(h.Decks) != len(names) {
		t.Errorf("%d decks described, %d in the registry", len(h.Decks), len(names))
	}
	for _, k := range []string{"usage", "examples", "aliases", "where", "who", "related", "sealedYes", "sealedNo", "adminOnly", "replaceable", "back", "things", "formatting", "popupRules"} {
		if h.Labels[k] == "" {
			t.Errorf("no label %q", k)
		}
	}
	if len(h.PopupRules) != 2 {
		t.Errorf("the list's rules are %d lines, not two", len(h.PopupRules))
	}
}

// "Things you can type" has a row for every kind the grammars define: each
// entity type (docs/MESSAGE-FORMAT.md section 3), each kind of block and
// inline span of Churr Markdown. A kind added to the grammar without a row
// here fails, and so does a row that covers a kind that does not exist.
func TestHelpCoversEveryKindTyped(t *testing.T) {
	h := readHelp(t)
	want := map[string]bool{"composer:command": true, "composer:literal": true, "composer:phrase": true}
	for _, v := range constValues(t, "message.go", "Entity") {
		want["entity:"+v] = true
	}
	for _, v := range typedConsts(t, "../markdown/doc.go", "BlockKind") {
		want["block:"+v] = true
	}
	for _, v := range typedConsts(t, "../markdown/doc.go", "InlineKind") {
		want["inline:"+v] = true
	}
	if len(want) < 30 {
		t.Fatalf("only %d kinds were read from the grammars: %v", len(want), want)
	}
	got := map[string]string{}
	ids := map[string]bool{}
	for _, list := range [][]helpThing{h.Things, h.Markdown} {
		for _, x := range list {
			if ids[x.ID] {
				t.Errorf("two rows are called %s", x.ID)
			}
			ids[x.ID] = true
			for _, k := range x.Covers {
				if !want[k] {
					t.Errorf("%s covers %s, which the grammars do not define", x.ID, k)
				}
				got[k] = x.ID
			}
			if x.Type == "" || x.Becomes == "" {
				t.Errorf("%s does not say what to type and what it becomes", x.ID)
			}
		}
	}
	for _, x := range h.Things {
		if x.Title == "" || x.Popup == "" || x.Example == nil || x.Example.Type == "" || x.Example.Then == "" || x.Sealed == nil {
			t.Errorf("%s lacks its title, what the list does, an example or what happens in a sealed chat", x.ID)
		}
		switch x.Live {
		case "", "patterns", "units":
		default:
			t.Errorf("%s: nothing is filled in as %q", x.ID, x.Live)
		}
	}
	for k := range want {
		if got[k] == "" {
			t.Errorf("nothing in Things you can type covers %s", k)
		}
	}
	units := 0
	for _, k := range h.MeasureKinds {
		units += len(k.Units)
	}
	if units < 20 {
		t.Errorf("only %d units are sorted into kinds", units)
	}
}

// constValues reads the string constants of a Go file whose names start
// with prefix.
func constValues(t *testing.T, path, prefix string) []string {
	return consts(t, path, func(name string, typ ast.Expr) bool { return strings.HasPrefix(name, prefix) })
}

// typedConsts reads the string constants of a Go file declared with type
// typ.
func typedConsts(t *testing.T, path, typ string) []string {
	return consts(t, path, func(_ string, ty ast.Expr) bool {
		id, ok := ty.(*ast.Ident)
		return ok && id.Name == typ
	})
}

func consts(t *testing.T, path string, keep func(name string, typ ast.Expr) bool) []string {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.CONST {
			continue
		}
		for _, s := range g.Specs {
			v := s.(*ast.ValueSpec)
			for i, n := range v.Names {
				if i >= len(v.Values) || !keep(n.Name, v.Type) {
					continue
				}
				lit, ok := v.Values[i].(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING {
					continue
				}
				s, err := strconv.Unquote(lit.Value)
				if err != nil {
					t.Fatal(err)
				}
				out = append(out, s)
			}
		}
	}
	return out
}
