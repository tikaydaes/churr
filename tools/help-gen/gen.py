#!/usr/bin/env python3
"""What /help says (rulings R67 and R74): testdata/commands/help.json, the
one source, written out for both clients.

    python3 tools/help-gen/gen.py

It writes the file as it is, unchanged, into:

- internal/web/static/shared/helptext.js, the web chat's copy;
- app/lib/core/commands/help_text.dart, the app's copy.

Neither is edited by hand. internal/model/help_test.go fails when either
differs from what this writes, and checks the source itself: a complete
entry for every command of commands.json and a row of "Things you can
type" for every kind the grammars define.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
SOURCE = os.path.join(ROOT, 'testdata', 'commands', 'help.json')

# The heads and tails both copies have; internal/model/help_test.go holds
# the same text.
JS_HEAD = ('// Generated by tools/help-gen/gen.py from testdata/commands/help.json.\n'
           '// Do not edit: change help.json and run the generator.\n\n'
           'export const HELP = ')
JS_TAIL = ';\n'
DART_HEAD = ('// Generated by tools/help-gen/gen.py from testdata/commands/help.json.\n'
             '// Do not edit: change help.json and run the generator.\n\n'
             '/// What /help says: testdata/commands/help.json as it is.\n'
             "const helpSource = r'''")
DART_TAIL = "''';\n"


def main():
    with open(SOURCE, encoding='utf-8') as f:
        text = f.read()
    json.loads(text)  # refuse a broken file before writing anything
    body = text.rstrip('\n')
    if "'''" in body:
        raise SystemExit("help.json may not hold ''' (it goes in a Dart raw string)")
    out = {
        os.path.join(ROOT, 'internal', 'web', 'static', 'shared', 'helptext.js'): JS_HEAD + body + JS_TAIL,
        os.path.join(ROOT, 'app', 'lib', 'core', 'commands', 'help_text.dart'): DART_HEAD + body + DART_TAIL,
    }
    for path, content in out.items():
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
