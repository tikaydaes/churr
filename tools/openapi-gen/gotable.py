"""Writes internal/api/operations_gen.go: the Go table of every operation in the contract.

build.py calls write(OPS, ROOT) once, after it has written docs/openapi.yaml, so the table always
comes from the same operations as the YAML. The server registers its handlers against this table by
operationId, which is what keeps a path or a method from drifting from the contract.

This file is separate from build.py so that the two can be edited independently. It reads only the
fields of an operation that lib.op() stores: id, method, path, auth, tag, page, st, res, raw.
"""
import os

HEADER = '''// Code generated by tools/openapi-gen/build.py from the API contract. DO NOT EDIT.
// Change the sources in tools/openapi-gen and run the build again.

package api

// Operations is every operation of docs/openapi.yaml, in the order of the
// contract. The server registers a handler for each by its ID, so a path or
// a method can never drift from the contract.
var Operations = []Operation{
'''

# How each value of an operation's `auth` is written in Go.
AUTH = {'none': 'AuthNone', 'optional': 'AuthOptional', 'user': 'AuthUser', 'pending': 'AuthPending',
        'web': 'AuthWeb', 'integration': 'AuthIntegration', 'hook': 'AuthHook'}


def success_status(o):
    """The status an operation answers with when it succeeds."""
    if o['raw'] is not None:
        return min(int(k) for k in o['raw'])
    if o['res'] is None:
        return 204
    return int(o['st'] or 200)


def table(ops):
    """The Go source: one line per operation, already in gofmt's form."""
    lines = [HEADER]
    for o in ops:
        fields = ['ID: "%s"' % o['id'], 'Method: "%s"' % o['method'].upper(), 'Path: "%s"' % o['path'],
                  'Auth: %s' % AUTH[o['auth']], 'Area: "%s"' % o['tag'], 'Success: %d' % success_status(o)]
        if o['page']:
            fields.append('Paging: "%s"' % o['page'])
        lines.append('\t{' + ', '.join(fields) + '},\n')
    lines.append('}\n')
    return ''.join(lines)


def write(ops, root):
    """Write the table, if the Go package it belongs to exists in this checkout."""
    out = os.path.join(root, 'internal', 'api', 'operations_gen.go')
    if os.path.isdir(os.path.dirname(out)):
        with open(out, 'w') as f:
            f.write(table(ops))


if __name__ == '__main__':
    # Run by itself, this rewrites only the Go table and leaves docs/openapi.yaml alone:
    #     python3 tools/openapi-gen/gotable.py
    import sys
    sys.dont_write_bytecode = True
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, here)
    from lib import OPS
    import schemas, ops_signin, ops_me, ops_chat, ops_bots, ops_sealed, ops_admin  # noqa: F401
    write(OPS, os.path.dirname(os.path.dirname(here)))
    print('internal/api/operations_gen.go: %d operations' % len(OPS))
